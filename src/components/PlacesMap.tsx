type Props = {
  results: Array<{ place: Place; km: number }>;
  userLocation: { lat: number; lng: number } | null;
  /** When set (area search), the map animates to this point. */
  focus?: { lat: number; lng: number } | null;
  /** Increment to fly the map back to the user's location. */
  recenterNonce?: number;
  onSelect: (id: string) => void;
};

export default function PlacesMap({
  results,
  userLocation,
  focus,
  recenterNonce,
  onSelect,
}: Props) {
  const { scheme } = useTheme();
  const mapRef = useRef<MapView>(null);
  // Wherever the user has panned/zoomed to; null until the first gesture.
  const [region, setRegion] = useState<MapRegion | null>(null);

  // Computed ONCE, from a ref: MapView reads `initialRegion` on mount and
  // never again, and the effects below own the camera after that. As a
  // useMemo over [userLocation, results] this changed identity on every GPS
  // fix, which dragged the pin grouping below along with it.
  const initialRegionRef = useRef<MapRegion | null>(null);
  if (initialRegionRef.current === null) {
    const centre = userLocation
      ? { lat: userLocation.lat, lng: userLocation.lng }
      : results[0]
        ? { lat: results[0].place.lat, lng: results[0].place.lng }
        : { lat: FALLBACK_REGION.latitude, lng: FALLBACK_REGION.longitude };
    initialRegionRef.current = {
      latitude: centre.lat,
      longitude: centre.lng,
      latitudeDelta: 0.05,
      longitudeDelta: 0.05,
    };
  }
  const initialRegion = initialRegionRef.current;

  // Which viewport the pins are grouped for BEFORE the map reports one of
  // its own. It has to follow the first GPS fix rather than stay on the
  // mount-time fallback, because the effect below glides the camera to the
  // user and `onRegionChangeComplete` only lands when that animation ends —
  // without this, a cold start showed London's pins for the whole flight to
  // wherever the user actually is.
  //
  // Keyed on the coordinates, not the object, so a fresh fix at the same
  // place doesn't invalidate anything downstream.
  const fallbackRegion = useMemo<MapRegion>(
    () =>
      userLocation
        ? {
            latitude: userLocation.lat,
            longitude: userLocation.lng,
            latitudeDelta: 0.05,
            longitudeDelta: 0.05,
          }
        : initialRegion,
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [userLocation?.lat, userLocation?.lng, initialRegion],
  );

  // On the first GPS fix after mount, glide from the fallback view to the
  // user. initialRegion is only read once by the native map, so without this
  // the map stayed parked on central London forever when the fix arrived
  // after mount (i.e. on almost every cold start).
  const hadLocationAtMount = useRef(userLocation !== null);
  const centredOnUser = useRef(false);
  useEffect(() => {
    if (
      userLocation &&
      !hadLocationAtMount.current &&
      !centredOnUser.current &&
      !focus
    ) {
      centredOnUser.current = true;
      mapRef.current?.animateToRegion(
        {
          latitude: userLocation.lat,
          longitude: userLocation.lng,
          latitudeDelta: 0.05,
          longitudeDelta: 0.05,
        },
        600,
      );
    }
  }, [userLocation, focus]);

  // "Back to my location" button: fly home whenever the nonce ticks. A
  // nonce (not a boolean) so pressing the button twice in a row still works.
  const lastRecenter = useRef(recenterNonce ?? 0);
  useEffect(() => {
    const nonce = recenterNonce ?? 0;
    if (nonce === lastRecenter.current) return;
    // Only mark this nonce handled once there's a location to animate to —
    // a tap that arrives before the first GPS fix must still fire the
    // animation once userLocation lands and this effect re-runs, rather
    // than being marked "done" here and silently dropped.
    if (!userLocation) return;
    lastRecenter.current = nonce;
    mapRef.current?.animateToRegion(
      {
        latitude: userLocation.lat,
        longitude: userLocation.lng,
        latitudeDelta: 0.05,
        longitudeDelta: 0.05,
      },
      600,
    );
  }, [recenterNonce, userLocation]);

  // Fly to the searched area when one is chosen.
  useEffect(() => {
    if (focus) {
      mapRef.current?.animateToRegion(
        {
          latitude: focus.lat,
          longitude: focus.lng,
          latitudeDelta: 0.04,
          longitudeDelta: 0.04,
        },
        400,
      );
    }
  }, [focus]);

  // What the viewport renders: individual pins while under budget, numbered
  // cluster bubbles for dense areas when zoomed out — every place in view is
  // always represented (see src/lib/mapPins.ts).
  //
  // Note the `??` is resolved OUTSIDE the memo: once the map has reported a
  // region, `fallbackRegion` moving with the user must not re-run the
  // grouping, and it can't, because it is no longer part of the input.
  const groupingRegion = region ?? fallbackRegion;
  const { singles, clusters } = useMemo(
    () => buildPinGroups(results, groupingRegion),
    [results, groupingRegion],
  );

  // FIXED MARKER POOL. Exactly MAX_MARKERS Marker components mount once and
  // are never added or removed afterwards — react-native-maps 1.20's marker
  // add/remove path crashes iOS under the new architecture (expo/expo#40856,
  // react-native-maps#5217, seen on an iPhone XR in Expo Go every time
  // clustering swapped the marker set). Region changes only MOVE markers
  // and swap their images; unused slots hide at opacity 0.
  //
  // WHICH slot each place lands in is remembered between renders (see
  // assignSlots). Filling them in list order meant one place leaving the
  // viewport shifted every later place down a slot — and since tapping a
  // marker nudges the map to fit its callout, which fires a region change,
  // the callout you had just opened would re-label itself with a nearby
  // masjid's name while staying anchored over the dot you tapped.
  const assignment = useRef<Map<string, number>>(new Map());
  const slots = useMemo<Slot[]>(() => {
    const next = assignSlots({ singles, clusters }, assignment.current);
    assignment.current = next.assignment;
    return next.slots;
  }, [singles, clusters]);

  return (
    <MapView
      ref={mapRef}
      style={styles.map}
      initialRegion={initialRegion}
      onRegionChangeComplete={(r) => setRegion(r)}
      showsUserLocation={userLocation !== null}
      userInterfaceStyle={scheme}
      // An EMPTY ARRAY for light, NOT undefined. MapView.java's setMapStyle
      // is `if (map != null && customMapStyleString != null)`, so a null
      // style is not "reset" — it is "do nothing", and the dark style stayed
      // applied for the rest of the session. `[]` works precisely because an
      // empty array is truthy in JS: the library's own
      // `customMapStyle ? JSON.stringify(...) : undefined` turns it into the
      // string "[]", which reaches Android as a style declaring no overrides,
      // i.e. the default map. Anything falsy here silently does nothing.
      // (Apple Maps ignores this prop and follows userInterfaceStyle above,
      // which is why only Android was stuck.)
      customMapStyle={scheme === "dark" ? DARK_MAP_STYLE : []}
      // Google Maps ships its own chrome, and all of it fought the app's --
      // on Android only, which is exactly the sort of divergence that goes
      // unnoticed when testing on an iPhone. All three are inert on Apple
      // Maps, so no Platform branch is needed.
      //
      // toolbarEnabled: pops two Google buttons over the bottom sheet on
      //   every pin tap.
      // showsMyLocationButton: a second "my location" FAB that lands under
      //   the search row and duplicates the app's own recenter control.
      // moveOnMarkerPress: nudges the camera on every pin tap, which fires
      //   onRegionChangeComplete and re-runs the pin grouping -- the exact
      //   callout churn the fixed slot pool above exists to avoid.
      toolbarEnabled={false}
      showsMyLocationButton={false}
      moveOnMarkerPress={false}
    >
      {slots.map((slot, index) => {
        if (slot?.kind === "cluster") {
          const { cluster } = slot;
          return (
            <Marker
              key={`slot-${index}`}
              coordinate={{ latitude: cluster.lat, longitude: cluster.lng }}
              opacity={1}
              anchor={{ x: 0.5, y: 0.5 }}
              image={CLUSTER_IMAGES[cluster.bucket]}
              tracksViewChanges={false}
              // Tap = zoom into the cluster's cell; the closer view either
              // resolves it into pins or into smaller clusters.
              onPress={() =>
                mapRef.current?.animateToRegion(
                  {
                    latitude: cluster.lat,
                    longitude: cluster.lng,
                    latitudeDelta: cluster.latitudeDelta,
                    longitudeDelta: cluster.longitudeDelta,
                  },
                  350,
                )
              }
              accessibilityLabel={`${cluster.count} places — tap to zoom in`}
            />
          );
        }
        if (slot) {
          const { place, km } = slot.candidate;
          return (
            <Marker
              key={`slot-${index}`}
              coordinate={{ latitude: place.lat, longitude: place.lng }}
              opacity={1}
              title={place.name}
              // Type + distance in the callout, so "is it walkable?" is
              // answered without leaving the map.
              description={`${PLACE_TYPE_LABELS[place.type]} · ${formatDistance(km)}`}
              onCalloutPress={() => onSelect(place.id)}
              image={PIN_IMAGES[place.type]}
              // Centre the dot on the coordinate (Android; iOS centres by
              // default).
              anchor={{ x: 0.5, y: 0.5 }}
              tracksViewChanges={false}
            />
          );
        }
        return (
          <Marker
            key={`slot-${index}`}
            coordinate={HIDDEN_COORDINATE}
            opacity={0}
            anchor={{ x: 0.5, y: 0.5 }}
            image={PIN_IMAGES.masjid}
            tracksViewChanges={false}
            // opacity: 0 removes a view from SIGHT, not from the
            // accessibility tree. Apple Maps annotation views are
            // accessibility elements by default, so in a sparse viewport
            // VoiceOver had up to 278 unlabelled parked pins to swipe past
            // before reaching anything real. `accessible` is the prop that
            // does the work; importantForAccessibility is the Android twin.
            accessible={false}
            importantForAccessibility="no"
          />
        );
      })}
    </MapView>
  );
}

const styles = StyleSheet.create({
  map: {
    flex: 1,
  },
});
